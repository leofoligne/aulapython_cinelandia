# Desenvolva um código Python que verifica se um valor é maior que o outro
# O usuáro deve digitar os dois valores
Valor1 = float(input("Qual o primeiro valor"))
Valor2 = float(input("Qual o segundo valor"))
if Valor1 > Valor2:
    print(f" O valor 1 de {Valor1} é maior que o valor 2 de {Valor2}")
elif Valor2 == Valor1:
    print(f"Os valores de {Valor1} e {Valor2} são iguais")
else:
    print(f" O valor 2 de {Valor2} é maior que o valor 1 de {Valor1}")
print("códgo alterado com sucesso")



